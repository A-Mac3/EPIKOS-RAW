pub(super) fn build(r: &Recipe) -> Style {
    Style {
        info: info(r.id, r.name, r.cat, r.world, r.desc, r.protect, r.swatch),
        texture: texture(r.tex[0], r.tex[1], r.tex[2], r.tex[3]),
        scene: ColorParams {
            hsl: hsl(r.hsl),
            wheels: wheels(r.wheels),
            saturation: r.sat,
            vibrance: r.vib,
            contrast: r.con,
            mono: r.mono,
        },
        skin: ColorParams { hsl: hsl(r.skin), ..Default::default() },
        atmosphere: AtmosphereParams {
            glow: r.glow[0],
            glow_radius: r.glow[1],
            glow_warmth: r.glow[2],
            haze: r.haze[0],
            haze_warmth: r.haze[1],
            ..Default::default()
        },
        film: film(r.film[0], r.film[1], r.film[2], r.film[3]),
    }
}
