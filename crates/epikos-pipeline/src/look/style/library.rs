type Bands = &'static [(usize, [f32; 3])];

pub(super) struct Recipe {
    id: &'static str,
    name: &'static str,
    cat: &'static str,
    world: &'static str,
    desc: &'static str,
    protect: f32,
    swatch: [&'static str; 2],
    hsl: Bands,
    wheels: Bands,
    sat: f32,
    vib: f32,
    con: f32,
    mono: f32,
    /// Clarity, micro-texture, blemish smoothing, specular balance.
    tex: [f32; 4],
    /// Fade, highlight roll, grain, grain size.
    film: [f32; 4],
    /// Glow amount, radius, warmth.
    glow: [f32; 3],
    /// Uniform haze and its warmth.
    haze: [f32; 2],
    /// Extra grade for skin only.
    skin: Bands,
}

